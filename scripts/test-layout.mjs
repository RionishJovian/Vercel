import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const source=fs.readFileSync(new URL('../web/app.html',import.meta.url),'utf8');
const css=fs.readFileSync(new URL('../web/assets/css/layout.css',import.meta.url),'utf8');
const section=(start,end)=>source.slice(source.indexOf(start),source.indexOf(end,source.indexOf(start)));
const context=vm.createContext({ME:{user:{user_role:'OWNER'}},SITE_EDITOR_ROLES:['OWNER','ADMIN','DEVELOPER'],esc:x=>String(x??''),Date});
vm.runInContext(section('function connectionIsFresh(','function siteOptionsHtml('),context);
let html=context.connPanel([]);
assert.equal((html.match(/id="conn-add"/g)||[]).length,1);
assert.ok(html.indexOf('id="conn-add"')<html.indexOf('class="panel-body"'),'connection action belongs in section header');
assert.ok(html.includes('panel-body record-form-grid'));
context.ME.user.user_role='VIEWER';
html=context.connPanel([]);
assert.ok(!html.includes('id="conn-add"') && !html.includes('id="conn-form"'));
assert.ok(source.includes('class="workspace-actions"'));
assert.ok(source.includes('/assets/css/layout.css?v='));
assert.ok(css.includes('[hidden] { display: none !important; }'));
assert.ok(css.includes('#tp-add, #pulse-strip):empty { display: none; }'));
assert.ok(!css.includes('#content > :empty'), 'empty map mounts and canvases must retain a measurable frame');
assert.ok(css.includes('flex-wrap: wrap'));
assert.ok(css.includes('grid-template-columns: minmax(0, 1fr)'));
assert.ok(!css.includes('gradient('));
console.log('Shared layout tests passed: owned actions, role visibility, section gaps, hidden/empty anchors, responsive forms, no gradients.');
