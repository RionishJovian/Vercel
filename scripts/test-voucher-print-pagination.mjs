import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const source=fs.readFileSync(new URL('../web/app.html',import.meta.url),'utf8');
const start=source.indexOf('function voucherPrintSelection('),end=source.indexOf('function wirePrintPreview(',start);
const context=vm.createContext({Math,Number,Array});
vm.runInContext(source.slice(start,end),context);
const rows=Array.from({length:205},(_,i)=>({code:`CODE-${i+1}`,status:'active'}));
const select=(size,page,status='available')=>context.voucherPrintSelection(rows,size,page,status);
assert.equal(select(100,1).vouchers.length,100);
assert.equal(select(100,2).vouchers[0].code,'CODE-101');
assert.equal(select(100,3).vouchers.length,5);
assert.equal(select(100,999).page,3);
assert.equal(select(1,2).vouchers[0].code,'CODE-2');
assert.equal(select(500,1).size,100);
assert.equal(select(0,1).size,100);
rows[0].status='used';
assert.equal(select(100,1).vouchers[0].code,'CODE-2');
assert.equal(select(100,1,'used').total,1);
assert.equal(select(100,1,'all').total,205);
const empty=context.voucherPrintSelection([],100,2,'available');
assert.equal(empty.page,1);assert.equal(empty.vouchers.length,0);
assert(source.includes('const real = selection().vouchers;'),'print must use current selection');
console.log('Voucher print pagination passed: 1–100 selections, disjoint pages, filters, bounds, empty selection and print wiring.');
