import assert from 'node:assert/strict';
import fs from 'node:fs';
import {createRequire} from 'node:module';
const {JSDOM}=createRequire(import.meta.url)('jsdom');

const source=fs.readFileSync('web/assets/js/network-control.js','utf8');
const dom=new JSDOM('<main id="host"></main>',{runScripts:'outside-only',url:'https://example.test'});
const {window}=dom;
window.eval(source);
const host=window.document.querySelector('#host');
let posts=0;
const inventory={write_enabled:true,wifi_write_enabled:false,interfaces:[{name:'ether1',type:'ether',running:true}],available:{pppoe_clients:true},objects:{pppoe_clients:[]}};
const api={get:async()=>({inventory}),post:async()=>{posts++;return {review:{steps:['Set routing'],warnings:[],confirmation:'test-only'}}}};
await window.MMNetwork.mount(host,'wan',[{device_id:'one',hardware_name:'Test router'}],true,api);
const device=host.querySelector('[data-router]');
device.value='one';
await device.onchange();
assert.equal(posts,0,'Loading inventory must not change the router');
assert.equal(host.querySelectorAll('[data-task]').length,2);
assert.equal(host.querySelector('[data-task="wan"]').getAttribute('aria-pressed'),'true');
assert.equal(host.querySelectorAll('fieldset').length,3,'WAN ports must be grouped separately');
host.querySelector('[data-task="pppoe_client"]').click();
assert.equal(host.querySelector('[data-task="pppoe_client"]').getAttribute('aria-pressed'),'true');
assert.equal(host.querySelectorAll('fieldset').length,1);
host.querySelector('[data-task="wan"]').click();
const form=host.querySelector('form');
form.reportValidity=()=>true;
await form.onsubmit({preventDefault(){}});
assert.equal(posts,1);
assert.equal(host.querySelector('[data-apply]').disabled,true,'Apply requires explicit consent');
form.dispatchEvent(new window.Event('input'));
assert.equal(host.querySelector('[data-apply]'),null,'Editing invalidates the review');
await window.MMNetwork.mount(host,'wifi',[{device_id:'one',hardware_name:'Test router'}],true,api);
host.querySelector('[data-router]').value='one';
await host.querySelector('[data-router]').onchange();
assert.match(host.querySelector('[data-settings]').textContent,/physical-radio acceptance/);
assert.equal(host.querySelector('form'),null,'The redesign must not bypass a rollout hold');
await window.MMNetwork.mount(host,'wan',[{device_id:'one',hardware_name:'Test router'}],false,api);
host.querySelector('[data-router]').value='one';
await host.querySelector('[data-router]').onchange();
assert.match(host.querySelector('[data-settings]').textContent,/owner or administrator/);
assert.equal(host.querySelector('form'),null);
console.log('Network layout passed: action selection, grouped fields, read-only loading, consent, stale review and rollout holds.');
