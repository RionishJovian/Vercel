import assert from "node:assert/strict";
import {readFile} from "node:fs/promises";
import {normalize,guestDocument,publishedDocument,applyTemplate,templates} from "../web/assets/js/media-appearance.js";
const invalid = normalize({theme:"url(evil)",accent:'"><script>',price:-1,duration:NaN});
assert.equal(invalid.theme,"charcoal"); assert.equal(invalid.accent,"#eeeeee");
assert.equal(invalid.price,1500); assert.equal(invalid.duration,24);
assert.equal(normalize({posterDensity:'invalid'}).posterDensity,'comfortable');
assert.ok(guestDocument({posterDensity:'compact',theme:'plum'}).includes('repeat(6,minmax(0,1fr))'));
assert.ok(guestDocument({posterDensity:'comfortable'}).includes('repeat(4,minmax(0,1fr))'));
const doc = guestDocument({name:'<img src=x onerror=alert(1)>',headline:"<script>alert(1)</script>",movies:false,series:false,music:false,featured:false});
assert.ok(doc.includes("&lt;img"));
assert.ok(!doc.includes("<script>"));
assert.ok(doc.includes("default-src 'none'"));
assert.ok(doc.includes("No categories selected."));
assert.ok(!doc.includes('class="poster'));
assert.ok(doc.includes("disabled"));
assert.ok(doc.includes("purchases and playback unavailable"));
assert.ok(guestDocument({price:2500,duration:12}).includes("2,500 MMK / 12 hours"));
const picture='data:image/png;base64,aGVsbG8=';
const editable={tiles:{movies:{title:'My <films>',caption:'A & B',image:picture}},posters:{0:{title:'Custom <title>',image:picture}},background:picture};
const custom=guestDocument(editable);
assert.ok(custom.includes('My &lt;films&gt;'));
assert.ok(custom.includes('A &amp; B'));
assert.ok(custom.includes('Custom &lt;title&gt;'));
assert.ok(custom.includes(`src="${picture}"`));
assert.ok(custom.includes('img-src data:'));
for (const image of ['https://evil.test/track','data:image/svg+xml;base64,aGVsbG8=','javascript:alert(1)',picture+'" onerror="alert(1)', 'data:image/png;base64,'+'A'.repeat(300000)]) {
  assert.equal(normalize({tiles:{movies:{image}},background:image}).tiles.movies.image,'');
  assert.equal(normalize({background:image}).background,'');
}
assert.equal(normalize({tiles:null,posters:null}).tiles.series.title,'TV Shows');
assert.equal(normalize({layout:'evil'}).layout,'shelves');
assert.equal(normalize({theme:'forest',...editable}).tiles.movies.image,picture);
assert.equal(normalize({theme:'forest'}).theme,'charcoal');
assert.equal(normalize({theme:'midnight'}).theme,'slate');
assert.equal(normalize({theme:'plum'}).theme,'charcoal');
for (const name of Object.keys(templates)) {
  const configured=applyTemplate(editable,name);
  assert.equal(configured.tiles.movies.image,picture);
  assert.equal(configured.tiles.movies.title,'My <films>');
  assert.equal(configured.posters[0].image,picture);
  assert.equal(configured.layout,templates[name].layout);
  assert.ok(!guestDocument(configured).includes('<script'));
  assert.ok(!guestDocument(configured).includes('gradient('),'no gradient guest designs');
  assert.ok(!guestDocument(configured).includes('backdrop-filter'),'no blur over artwork');
  assert.ok(guestDocument(configured).includes('filter:none;opacity:1'),'artwork is not tinted');
}
assert.ok(!custom.includes('gradient('),'background uploads have no gradient overlay');
assert.ok(!guestDocument({}).includes('✦'),'no decorative generated-art symbols');
assert.ok(guestDocument({}).includes('Add cover artwork'),'honest text-only empty artwork');
const css=await readFile(new URL('../web/assets/css/media-appearance.css',import.meta.url),'utf8');
assert.ok(!css.includes('gradient('),'media workspace CSS has no gradients');
assert.ok(guestDocument(applyTemplate({},'cinema')).includes('aspect-ratio:16/9'));
console.log("Media preview checks passed: escaped content, validated theme/colour, sections, sample pricing and no live purchases.");
const published=publishedDocument({name:'<script>evil</script>',price:2500,duration:12,featured:true});
assert.ok(!published.includes('Sample title')&&!published.includes('The quiet coast'));
assert.ok(!published.includes('Example categories')&&!published.includes('DESIGN PREVIEW'));
assert.ok(published.includes('purchases and playback are not available yet'));
assert.ok(published.includes('No payment is collected'));
assert.ok(published.includes('2,500 MMK / 12 hours'));
assert.ok(!published.includes('<script>'));
console.log('Published page checks passed: no sample catalog, no payment/playback promises, escaped design.');
