import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
// Import source as ESM independently of the repository package type.
let source=await readFile(new URL('../web/assets/js/media-dashboard.js',import.meta.url),'utf8');
source=source.replace(/^import .*;\n/gm,'');
const {online,libraryCards}=await import('data:text/javascript;base64,'+Buffer.from(source).toString('base64'));
const now=Date.now();
assert.equal(online({last_seen_at:new Date(now-5000).toISOString(),expires_at:new Date(now+60000).toISOString()},now),true);
assert.equal(online({last_seen_at:new Date(now-60000).toISOString(),expires_at:new Date(now+60000).toISOString()},now),false);
assert.equal(online({revoked_at:new Date(now).toISOString(),last_seen_at:new Date(now).toISOString(),expires_at:new Date(now+60000).toISOString()},now),false);
assert.equal(online({},now),false);
assert.match(libraryCards([]),/No libraries yet/);
const cards=libraryCards([{Name:'<script>alert(1)</script>',CollectionType:'"',Locations:['<img src=x onerror=alert(1)>']}]);
assert.match(cards,/media-library-card/);
assert.ok(!source.includes('<h2>Magic Media</h2>'),'duplicate workspace heading');
assert.match(source,/media-connection-layout/);
assert.match(source,/media-libraries-layout/);
assert.match(source,/Dashboard → Advanced → API Keys/);
assert.match(source,/name="confirm" required/);
assert.ok(!cards.includes('<script>')&&!cards.includes('<img'));
assert.ok(cards.includes('&lt;script&gt;'));
console.log('Media dashboard status and rendering checks passed.');
